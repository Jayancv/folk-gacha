// Package seeding loads reference data: every card season's catalog (templates,
// season, cards) and the merge recipes. Safe to run again: nothing is duplicated,
// existing cards are never changed, and recipe outputs are updated in place.
package seeding

import (
	"context"
	"encoding/json"
	"fmt"
	"io/fs"
	"path"
	"sort"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"

	"cardgame/server/internal/game"
	"cardgame/server/internal/store"
)

// Sources are the embedded seed files (tests can pass their own).
type Sources struct {
	// Seasons holds <season>/seed.sql files generated by cmd/seasongen.
	Seasons fs.FS
	// Recipes is seed/recipes.json.
	Recipes []byte
}

type Result struct {
	// Seasons maps season id to its card count in the database after seeding.
	Seasons map[string]int64
	Recipes int
}

func Run(ctx context.Context, pool *pgxpool.Pool, src Sources) (Result, error) {
	res := Result{Seasons: map[string]int64{}}

	files, err := fs.Glob(src.Seasons, "*/seed.sql")
	if err != nil {
		return res, err
	}
	sort.Strings(files)
	for _, f := range files {
		sql, err := fs.ReadFile(src.Seasons, f)
		if err != nil {
			return res, err
		}
		// Each file is one transaction of idempotent inserts (BEGIN … COMMIT inside).
		if _, err := pool.Exec(ctx, string(sql)); err != nil {
			return res, fmt.Errorf("season %s: %w", f, err)
		}
		season := path.Dir(f)
		n, err := store.New(pool).CountSeasonCards(ctx, season)
		if err != nil {
			return res, err
		}
		res.Seasons[season] = n
	}

	n, err := seedRecipes(ctx, pool, src.Recipes)
	res.Recipes = n
	return res, err
}

func seedRecipes(ctx context.Context, pool *pgxpool.Pool, raw []byte) (int, error) {
	var file struct {
		Recipes []game.RecipeSpec `json:"recipes"`
	}
	if err := json.Unmarshal(raw, &file); err != nil {
		return 0, fmt.Errorf("recipes.json: %w", err)
	}

	q := store.New(pool)
	ids, err := q.ListTemplateIDs(ctx)
	if err != nil {
		return 0, err
	}
	known := make(map[string]bool, len(ids))
	for _, id := range ids {
		known[id] = true
	}
	recipes, err := game.NormalizeRecipes(file.Recipes, known)
	if err != nil {
		return 0, fmt.Errorf("recipes.json: %w", err)
	}

	// All recipes or none.
	err = pgx.BeginFunc(ctx, pool, func(tx pgx.Tx) error {
		qtx := store.New(tx)
		for _, r := range recipes {
			if err := qtx.UpsertRecipe(ctx, store.UpsertRecipeParams{InputA: r.A, InputB: r.B, OutputTemplateID: r.Output}); err != nil {
				return fmt.Errorf("recipe %s + %s: %w", r.A, r.B, err)
			}
		}
		return nil
	})
	if err != nil {
		return 0, err
	}
	return len(recipes), nil
}
